
def add_two_number(first_number, second_number):

    return first_number + second_number


def subtract_two_number(first_number, second_number):

    return first_number - second_number


def divide_two_number(first_number, second_number):

    return first_number / second_number


def multiply_two_number(first_number, second_number):

    return first_number * second_number


def exponent_two_number(first_number, power):

    return first_number ** power






addition_result = add_two_number(57, 24)
print("Addition:",addition_result)

subtraction_result = subtract_two_number(57, 24)
print("Subtraction:", subtraction_result)

divide_result = divide_two_number(57, 24)
print("Division:", divide_result)

multiply_result = multiply_two_number(57, 24)
print("Multiplication:", multiply_result)

exponent_result = exponent_two_number(57, 3)
print("Exponential:", exponent_result)














